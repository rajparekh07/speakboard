#!/usr/bin/env python3
"""Validate a Speakboard token export.

    python3 validate-tokens.py speakboard-tokens.json --schema speakboard-tokens.schema.json
                               [--expect-sha256 HEX] [--no-measured]

Exit codes: 0 every check passed; 1 a check failed; 2 bad arguments or an
unreadable input file.

Standard library only. Two layers of checks:

1. The schema mirror (`mirror_errors`). A plain-Python transcription of every
   rule in speakboard-tokens.schema.json, written to reach the same verdict as
   a JSON Schema 2020-12 validator on any input. With --schema, the id lists
   the schema was generated with (device classes, sources, tokens) are read
   from it with plain JSON. test-validator.py checks the mirror against the
   `jsonschema` package on about 37,000 mutations generated by walking
   the export and the schema; any difference fails the test.
2. Checks a schema cannot express (`extra_errors`), always run:
   - sha256 equals --expect-sha256, when given;
   - no token id is a prefix of another; no segment becomes a reserved Swift
     type name; no last segment is a Swift keyword;
   - numbers are finite, and counts are integer literals (not 3.0);
   - aliasOf: target has the same axes and unit, values equal in every cell;
   - deviceClasses keys in the same order as axes.deviceClass;
   - derived geometry: the six identity tokens, the ratio-based widths and the
     two colour copies are recomputed; their estimated cells must be method
     derived with source derived; a derived cell may not claim more
     confidence than its inputs; a measured cell of an identity token must
     agree with its inputs within its own tolerance plus the inputs';
   - method derived with a source other than derived is allowed only on
     systemStrip.height, iphone-375x812, portrait;
   - --no-measured: no measured leaf anywhere, device classes included;
   - summary matches a recount.

Because layer 1 is always run, the verdict does not depend on whether
`jsonschema` is installed. When it is installed and --schema is given, the
real schema also runs, as a cross-check. Without --schema, layer 1 cannot
check the id lists, so always pass it.
"""
import hashlib
import json
import math
import re
import sys
from collections import Counter

AXES_SHAPES = [[], ["appearance"], ["deviceClass", "orientation"]]
UNITS = ["pt", "ms", "ratio", "count", "srgb-hex8", "uifont-weight", "font-family", "glyph-id"]
TOL_UNIT_FOR = {"pt": "pt", "ms": "ms", "ratio": "ratio", "count": "count", "srgb-hex8": "deltaE2000",
                "uifont-weight": "weightSteps", "font-family": "enum", "glyph-id": "enum"}
TOL_UNITS = sorted(set(TOL_UNIT_FOR.values()))
WEIGHTS = ["ultraLight", "thin", "light", "regular", "medium", "semibold", "bold", "heavy", "black"]
METHODS = ["recalled", "derived", "assumed", "guessed", "placeholder"]
CONFIDENCES = ["medium", "low", "none"]
CONF_RANK = {"none": 0, "low": 1, "medium": 2, "measured": 3}
SOURCE_KINDS = ["public-documentation", "recall-unverified", "derivation", "none", "capture"]
TOP_REQUIRED = ["$schema", "schemaVersion", "tokenSetVersion", "platform", "units", "toleranceUnits", "axes", "sources", "ios"]
TOP_PROPS = set(TOP_REQUIRED) | {"status", "ticket", "designSystem", "summary"}
TOKEN_KEYS = ["group", "description", "appleMatching", "unit", "axes", "values"]
P_TOKEN_ID = r"^[a-z][a-zA-Z0-9]*(\.[a-z][a-zA-Z0-9]*)+$"
P_GLYPH = r"^[a-z][a-z0-9]*(\.[a-z0-9]+)*$"
P_HEX8 = r"^#[0-9A-F]{8}$"
P_IOS = r"^[0-9]{2}(\.[0-9]+){0,2}$"
P_SCHEMA_VERSION = r"^1\.[0-9]+\.[0-9]+$"
P_SEMVER = r"^[0-9]+\.[0-9]+\.[0-9]+$"
P_IOS_KEY = r"^[0-9]{2}$"
SWIFT_TYPE_RESERVED = {"Type", "Self", "Protocol", "Any", "AnyObject"}
SWIFT_KEYWORDS = {"associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout",
                  "internal", "let", "open", "operator", "private", "protocol", "public", "rethrows", "static", "struct",
                  "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do", "else", "fallthrough",
                  "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while", "as", "catch", "false", "is",
                  "nil", "super", "self", "throw", "throws", "true", "try", "Type", "Self"}
OUTSIDE_DERIVED = {("systemStrip.height", "iphone-375x812", "portrait")}


# ------------------------------------------------- JSON Schema primitives
def is_obj(v):
    return isinstance(v, dict)


def is_str(v):
    return isinstance(v, str)


def is_num(v):  # JSON Schema "number": any int or float, not a boolean (NaN and inf included)
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def finite(v):
    return is_num(v) and math.isfinite(v)


def is_integer(v):  # JSON Schema "integer": also a float with no fractional part
    return (isinstance(v, int) and not isinstance(v, bool)) or (isinstance(v, float) and math.isfinite(v) and v.is_integer())


def j_equal(a, b):
    """JSON equality as JSON Schema defines it: booleans are not numbers."""
    if isinstance(a, bool) or isinstance(b, bool):
        return isinstance(a, bool) and isinstance(b, bool) and a == b
    if is_num(a) and is_num(b):
        return a == b
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(j_equal(x, y) for x, y in zip(a, b))
    if is_obj(a) and is_obj(b):
        return a.keys() == b.keys() and all(j_equal(a[k], b[k]) for k in a)
    return type(a) is type(b) and a == b


def in_enum(v, options):
    return any(j_equal(v, o) for o in options)


def pat_ok(v, p):
    """A patterned string in this schema: the pattern (searched, as JSON Schema does) and no whitespace."""
    return is_str(v) and re.search(p, v) is not None and re.search(r"\s", v) is None


def ne_str(v):
    return is_str(v) and len(v) >= 1


def walk(values, depth, path=()):
    if depth == 0:
        yield path, values
    elif is_obj(values):
        for k, v in values.items():
            yield from walk(v, depth - 1, path + (k,))


def at(values, path):
    for k in path:
        values = values[k]
    return values


# ------------------------------------------------------------ layer 1
def schema_ids(schema):
    """The id lists a generated schema carries, read with plain JSON."""
    try:
        d = schema["$defs"]
        ids = {"deviceClasses": d["deviceClassId"]["enum"],
               "sources": schema["properties"]["sources"]["required"],
               "tokens": d["iosVersion"]["properties"]["tokens"]["required"]}
    except (KeyError, TypeError):
        return None
    if not all(isinstance(v, list) and all(is_str(x) for x in v) for v in ids.values()):
        return None
    return ids


class Mirror:
    def __init__(self, ids):
        self.ids = ids
        self.errors = []

    def err(self, m):
        self.errors.append(m)

    def obj(self, w, v, required, allowed=None):
        """type object, required keys, additionalProperties false (when allowed is given). Returns v is an object."""
        if not is_obj(v):
            self.err(f"{w}: must be an object")
            return False
        for k in required:
            if k not in v:
                self.err(f"{w}: missing required key {k}")
        if allowed is not None:
            for k in v:
                if k not in allowed:
                    self.err(f"{w}: unknown key {k}")
        return True

    def tolerance(self, w, t):
        if self.obj(w, t, ["plusMinus", "unit"], {"plusMinus", "unit"}):
            if "plusMinus" in t and not (is_num(t["plusMinus"]) and not (t["plusMinus"] < 0)):
                self.err(f"{w}: plusMinus must be a number >= 0")
            if "unit" in t and not in_enum(t["unit"], TOL_UNITS):
                self.err(f"{w}: tolerance unit not in {TOL_UNITS}")

    def prov_valid_as(self, kind, p):
        """Does p validate against provMeasured / provEstimated / provInvented? Returns the error list."""
        sub = Mirror(self.ids)
        w = "provenance"
        if kind == "measured":
            req, allowed = ["kind", "ios", "device", "capture"], {"kind", "ios", "device", "capture", "capturedAt", "method", "tolerance"}
        elif kind == "estimated":
            req, allowed = ["kind", "source", "tolerance", "confidence", "method"], {"kind", "source", "tolerance", "confidence", "method", "derivation", "note"}
        else:
            req, allowed = ["kind", "rationale"], {"kind", "rationale", "decidedIn", "aliasOf"}
        if not sub.obj(w, p, req, allowed):
            return sub.errors
        if "kind" in p and not j_equal(p["kind"], kind):
            sub.err(f"{w}: kind is not {kind}")
        if kind == "measured":
            if "ios" in p and not pat_ok(p["ios"], P_IOS):
                sub.err(f"{w}: measured ios must look like 26 or 26.1 or 26.1.2")
            for k in ("device", "capture", "capturedAt", "method"):
                if k in p and not ne_str(p[k]):
                    sub.err(f"{w}: measured {k} must be a non-empty string")
            if "tolerance" in p:
                sub.tolerance(w + ".tolerance", p["tolerance"])
        elif kind == "estimated":
            if "source" in p and not in_enum(p["source"], self.ids["sources"] if self.ids else []):
                sub.err(f"{w}: unknown source {p['source']!r}")
            if "tolerance" in p:
                sub.tolerance(w + ".tolerance", p["tolerance"])
            if "confidence" in p and not in_enum(p["confidence"], CONFIDENCES):
                sub.err(f"{w}: confidence not in {CONFIDENCES}")
            if "method" in p and not in_enum(p["method"], METHODS):
                sub.err(f"{w}: method not in {METHODS}")
            for k in ("derivation", "note"):
                if k in p and not ne_str(p[k]):
                    sub.err(f"{w}: {k} must be a non-empty string")
            # if/then, with JSON Schema's semantics: an absent key satisfies the "if"
            if ("method" not in p or j_equal(p["method"], "derived")) and "derivation" not in p:
                sub.err(f"{w}: method derived without a derivation")
            if "source" not in p or j_equal(p["source"], "no-basis"):
                if "method" in p and not j_equal(p["method"], "placeholder"):
                    sub.err(f"{w}: source no-basis needs method placeholder")
                if "confidence" in p and not j_equal(p["confidence"], "none"):
                    sub.err(f"{w}: source no-basis needs confidence none")
        else:
            if "rationale" in p and not ne_str(p["rationale"]):
                sub.err(f"{w}: invented provenance needs a non-empty rationale")
            if "decidedIn" in p and not ne_str(p["decidedIn"]):
                sub.err(f"{w}: decidedIn must be a non-empty string")
            if "aliasOf" in p and not in_enum(p["aliasOf"], self.ids["tokens"] if self.ids else []):
                sub.err(f"{w}: aliasOf {p['aliasOf']!r} is not a token")
        return sub.errors

    def provenance(self, w, p, kinds):
        """oneOf over the kinds allowed here; reports the matching branch's errors, or why none matched."""
        results = {k: self.prov_valid_as(k, p) for k in kinds}
        ok = [k for k, e in results.items() if not e]
        if len(ok) == 1:
            return ok[0]
        if len(ok) > 1:
            self.err(f"{w}: provenance matches more than one kind")
            return None
        k = p.get("kind") if is_obj(p) else None
        if is_str(k) and k in results:
            for e in results[k]:
                self.err(f"{w}: {e}")
        else:
            self.err(f"{w}: provenance kind {k!r} is not allowed here (allowed: {', '.join(kinds)})")
        return None

    def leaf(self, w, lf, unit, apple):
        if not self.obj(w, lf, ["value", "unit", "provenance"], {"value", "unit", "provenance"}):
            return
        if "value" in lf:
            v = lf["value"]
            ok = {"pt": is_num, "ms": is_num, "ratio": is_num, "count": is_integer,
                  "srgb-hex8": lambda x: pat_ok(x, P_HEX8), "uifont-weight": lambda x: in_enum(x, WEIGHTS),
                  "font-family": lambda x: j_equal(x, "system"), "glyph-id": lambda x: pat_ok(x, P_GLYPH)}[unit](v)
            if not ok:
                self.err(f"{w}: value {v!r} is not a valid {unit}")
        if "unit" in lf and not j_equal(lf["unit"], unit):
            self.err(f"{w}: leaf unit {lf['unit']!r} differs from token unit {unit!r}")
        if "provenance" in lf:
            p = lf["provenance"]
            # provenance: allOf [oneOf kinds, {kind restriction, tolerance.unit const}]
            self.provenance(w, p, ["measured", "estimated", "invented"])
            if is_obj(p):
                if "kind" in p:
                    allowed = ["measured", "estimated"] if apple else ["invented"]
                    if not in_enum(p["kind"], allowed):
                        self.err(f"{w}: {'Apple-matching' if apple else 'our'} token holds a {p['kind']!r} value")
                t = p.get("tolerance")
                if is_obj(t) and "unit" in t and not j_equal(t["unit"], TOL_UNIT_FOR[unit]):
                    self.err(f"{w}: tolerance unit {t['unit']!r} does not fit unit {unit}")

    def token(self, tid, t, classes):
        if not self.obj(tid, t, TOKEN_KEYS, set(TOKEN_KEYS)):
            return
        for k in ("group", "description"):
            if k in t and not is_str(t[k]):
                self.err(f"{tid}: {k} must be a string")
        if "appleMatching" in t and not isinstance(t["appleMatching"], bool):
            self.err(f"{tid}: appleMatching must be a boolean")
        if "unit" in t and not in_enum(t["unit"], UNITS):
            self.err(f"{tid}: unknown unit {t['unit']!r}")
        if "axes" in t and not in_enum(t["axes"], AXES_SHAPES):
            self.err(f"{tid}: axes {t['axes']!r} not one of the three shapes")
        if "values" in t and not is_obj(t["values"]):
            self.err(f"{tid}: values must be an object")
        # The schema's conditional: leaves are checked only when axes, unit and appleMatching are all valid.
        if not ("axes" in t and "unit" in t and "appleMatching" in t and "values" in t):
            return
        if not (in_enum(t["axes"], AXES_SHAPES) and in_enum(t["unit"], UNITS) and isinstance(t["appleMatching"], bool)):
            return
        axes, unit, apple = t["axes"], t["unit"], t["appleMatching"]
        allowed = {"deviceClass": classes, "orientation": ["portrait", "landscape"], "appearance": ["light", "dark"]}

        def node(w, v, depth):
            if depth == len(axes):
                self.leaf(w, v, unit, apple)
                return
            keys = allowed[axes[depth]]
            if self.obj(w, v, keys, set(keys)):
                for k in keys:
                    if k in v:
                        node(f"{w}/{k}" if depth else f"{w}[{k}", v[k], depth + 1)
        node(tid, t["values"], 0)

    def device_class(self, w, dc):
        if not self.obj(w, dc, ["screen", "homeIndicator", "models", "provenance"], {"screen", "homeIndicator", "models", "provenance"}):
            return
        sc = dc.get("screen")
        if "screen" in dc and self.obj(w + ".screen", sc, ["width", "height", "unit", "orientation"], {"width", "height", "unit", "orientation"}):
            for k in ("width", "height"):
                if k in sc and not is_num(sc[k]):
                    self.err(f"{w}.screen.{k} must be a number")
            if "unit" in sc and not j_equal(sc["unit"], "pt"):
                self.err(f"{w}.screen.unit must be pt")
            if "orientation" in sc and not j_equal(sc["orientation"], "portrait"):
                self.err(f"{w}.screen.orientation must be portrait")
        if "homeIndicator" in dc and not isinstance(dc["homeIndicator"], bool):
            self.err(f"{w}.homeIndicator must be a boolean")
        if "models" in dc:
            m = dc["models"]
            if not (isinstance(m, list) and len(m) >= 1 and all(is_str(x) for x in m)):
                self.err(f"{w}.models must be a non-empty list of strings")
        if "provenance" in dc:
            self.provenance(w, dc["provenance"], ["measured", "estimated"])

    def run(self, doc):
        if not self.obj("top level", doc, TOP_REQUIRED, TOP_PROPS):
            return
        if self.ids is None:
            # Without --schema the id lists are unknown: fall back to the file's own lists,
            # so only the id-list rules go unchecked.
            ax = doc.get("axes") if is_obj(doc.get("axes")) else {}
            dcl = ax.get("deviceClass") if isinstance(ax.get("deviceClass"), list) else []
            srcs = list(doc["sources"]) if is_obj(doc.get("sources")) else []
            toks = []
            if is_obj(doc.get("ios")):
                for v in doc["ios"].values():
                    if is_obj(v) and is_obj(v.get("tokens")):
                        toks += list(v["tokens"])
            self.ids = {"deviceClasses": [c for c in dcl if is_str(c)], "sources": srcs, "tokens": toks, "fallback": True}
        ids = self.ids
        for k in ("$schema", "status", "ticket", "designSystem"):
            if k in doc and not is_str(doc[k]):
                self.err(f"{k} must be a string")
        if "schemaVersion" in doc and not pat_ok(doc["schemaVersion"], P_SCHEMA_VERSION):
            self.err("schemaVersion must be 1.x.y")
        if "tokenSetVersion" in doc and not pat_ok(doc["tokenSetVersion"], P_SEMVER):
            self.err("tokenSetVersion must be x.y.z")
        if "platform" in doc and not j_equal(doc["platform"], "iphone"):
            self.err("platform must be \"iphone\"")
        if "units" in doc and self.obj("units", doc["units"], UNITS):
            if not all(is_str(v) for v in doc["units"].values()):
                self.err("units must map names to strings")
        if "toleranceUnits" in doc and self.obj("toleranceUnits", doc["toleranceUnits"], []):
            if not all(is_str(v) for v in doc["toleranceUnits"].values()):
                self.err("toleranceUnits must map names to strings")
        if "summary" in doc and not is_obj(doc["summary"]):
            self.err("summary must be an object")
        if "axes" in doc and self.obj("axes", doc["axes"], ["deviceClass", "orientation", "appearance"],
                                      {"deviceClass", "orientation", "appearance"}):
            a = doc["axes"]
            if not ids.get("fallback") and "deviceClass" in a and not j_equal(a["deviceClass"], ids["deviceClasses"]):
                self.err("axes.deviceClass differs from the schema's device class list")
            if "orientation" in a and not j_equal(a["orientation"], ["portrait", "landscape"]):
                self.err("axes.orientation must be [portrait, landscape]")
            if "appearance" in a and not j_equal(a["appearance"], ["light", "dark"]):
                self.err("axes.appearance must be [light, dark]")
        if "sources" in doc:
            srcs = doc["sources"]
            req = [] if ids.get("fallback") else ids["sources"]
            if self.obj("sources", srcs, req, None if ids.get("fallback") else set(req)):
                for sid, s in srcs.items():
                    w = f"sources.{sid}"
                    if self.obj(w, s, ["title", "kind", "url", "note"], {"title", "kind", "url", "note"}):
                        if "title" in s and not is_str(s["title"]):
                            self.err(f"{w}.title must be a string")
                        if "note" in s and not is_str(s["note"]):
                            self.err(f"{w}.note must be a string")
                        if "url" in s and not (s["url"] is None or is_str(s["url"])):
                            self.err(f"{w}.url must be a string or null")
                        if "kind" in s and not in_enum(s["kind"], SOURCE_KINDS):
                            self.err(f"{w}.kind not in {SOURCE_KINDS}")
        if "ios" in doc and self.obj("ios", doc["ios"], []):
            if len(doc["ios"]) < 1:
                self.err("ios has no version")
            classes = ids["deviceClasses"] or []
            for ver, vdoc in doc["ios"].items():
                if not pat_ok(ver, P_IOS_KEY):
                    self.err(f"ios key {ver!r} is not two digits")
                w = f"ios.{ver}"
                if not self.obj(w, vdoc, ["target", "referenceDeviceClass", "deviceClasses", "tokens"],
                                {"target", "referenceDeviceClass", "deviceClasses", "tokens"}):
                    continue
                if "target" in vdoc and not is_str(vdoc["target"]):
                    self.err(f"{w}.target must be a string")
                if "referenceDeviceClass" in vdoc and not in_enum(vdoc["referenceDeviceClass"], classes):
                    self.err(f"{w}.referenceDeviceClass is not a device class")
                if "deviceClasses" in vdoc and self.obj(w + ".deviceClasses", vdoc["deviceClasses"], classes, set(classes)):
                    for cid in classes:
                        if cid in vdoc["deviceClasses"]:
                            self.device_class(f"deviceClasses.{cid}", vdoc["deviceClasses"][cid])
                if "tokens" in vdoc:
                    req = [] if ids.get("fallback") else ids["tokens"]
                    if self.obj(w + ".tokens", vdoc["tokens"], req):
                        for tid, t in vdoc["tokens"].items():
                            if not pat_ok(tid, P_TOKEN_ID):
                                self.err(f"{tid!r}: id does not match the token id pattern")
                            self.token(tid, t, classes)


def mirror_errors(doc, ids):
    m = Mirror(ids)
    m.run(doc)
    return m.errors


# ------------------------------------------------------------ layer 2
def up(x):
    return math.ceil(round(x * 10, 6)) / 10


def extra_errors(doc, no_measured):
    """Checks a schema cannot express. Defensive: skips anything layer 1 already rejects as malformed."""
    errors = []
    err = errors.append
    if not is_obj(doc):
        return errors

    def finite_walk(v, w):
        if isinstance(v, float) and not math.isfinite(v):
            err(f"{w}: number is not finite")
        elif is_obj(v):
            for k, x in v.items():
                finite_walk(x, f"{w}.{k}")
        elif isinstance(v, list):
            for i, x in enumerate(v):
                finite_walk(x, f"{w}[{i}]")
    finite_walk(doc, "$")

    axes_def = doc.get("axes") if is_obj(doc.get("axes")) else {}
    by_tok, by_leaf, conf, meth = Counter(), Counter(), Counter(), Counter()
    ios = doc.get("ios") if is_obj(doc.get("ios")) else {}
    for ver, vdoc in ios.items():
        if not is_obj(vdoc):
            continue
        dcs = vdoc.get("deviceClasses") if is_obj(vdoc.get("deviceClasses")) else {}
        if list(dcs) != axes_def.get("deviceClass"):
            err(f"ios {ver}: deviceClasses keys are not in the order of axes.deviceClass")
        for cid, dc in dcs.items():
            p = dc.get("provenance") if is_obj(dc) else None
            if no_measured and is_obj(p) and p.get("kind") == "measured":
                err(f"deviceClasses.{cid}: measured value present under --no-measured")
        tokens = vdoc.get("tokens") if is_obj(vdoc.get("tokens")) else {}
        ids = sorted(tokens)
        for a in ids:
            for b in ids:
                if b != a and b.startswith(a + "."):
                    err(f"{a} is a prefix of {b}")
            segs = a.split(".")
            for s in segs[:-1]:
                if s and s[0].upper() + s[1:] in SWIFT_TYPE_RESERVED:
                    err(f"{a}: segment '{s}' becomes a reserved Swift type name")
            if segs[-1] in SWIFT_KEYWORDS:
                err(f"{a}: last segment '{segs[-1]}' is a Swift keyword")
        for tid, t in tokens.items():
            if not (is_obj(t) and t.get("axes") in AXES_SHAPES and is_obj(t.get("values"))):
                continue
            axes, unit = t["axes"], t.get("unit")
            kinds = set()
            for p, lf in walk(t["values"], len(axes)):
                if len(p) != len(axes) or not is_obj(lf) or not is_obj(lf.get("provenance")):
                    continue
                where = f"{tid}[{'/'.join(p)}]" if p else tid
                pv = lf["provenance"]
                k = pv.get("kind")
                if not is_str(k):
                    continue
                kinds.add(k)
                by_leaf[k] += 1
                if k == "estimated":
                    if is_str(pv.get("confidence")):
                        conf[pv["confidence"]] += 1
                    if is_str(pv.get("method")):
                        meth[pv["method"]] += 1
                    if pv.get("method") == "derived" and pv.get("source") != "derived" and (tid,) + p not in OUTSIDE_DERIVED:
                        err(f"{where}: method derived with source {pv.get('source')!r}; only systemStrip.height on iphone-375x812 portrait may derive from an outside figure")
                if k == "measured" and no_measured:
                    err(f"{where}: measured value present under --no-measured")
                if unit == "count" and not (isinstance(lf.get("value"), int) and not isinstance(lf.get("value"), bool)):
                    err(f"{where}: count must be an integer literal")
                alias = pv.get("aliasOf") if k == "invented" else None
                if is_str(alias) and is_obj(tokens.get(alias)):
                    tgt = tokens[alias]
                    if tgt.get("axes") != axes or tgt.get("unit") != unit:
                        err(f"{where}: aliasOf {alias} has different axes or unit")
                    else:
                        try:
                            tv = at(tgt["values"], p)["value"]
                        except (KeyError, TypeError):
                            err(f"{where}: aliasOf {alias} has no cell {'/'.join(p)}")
                        else:
                            if not j_equal(tv, lf.get("value")):
                                err(f"{where}: value {lf.get('value')!r} differs from its alias target {alias} ({tv!r})")
            if kinds == {"measured", "estimated"}:
                by_tok["measuredAndEstimated"] += 1
            elif len(kinds) == 1:
                by_tok[next(iter(kinds))] += 1
            elif kinds:
                err(f"{tid}: mixes provenance kinds {sorted(kinds)}")
        errors.extend(derived_errors(tokens, dcs))

    s = doc.get("summary")
    if is_obj(s):
        want = {"tokens": {k: by_tok.get(k, 0) for k in ("measured", "estimated", "measuredAndEstimated", "invented")},
                "values": {k: by_leaf.get(k, 0) for k in ("measured", "estimated", "invented")},
                "estimatedValuesByConfidence": {k: conf.get(k, 0) for k in CONFIDENCES},
                "estimatedValuesByMethod": {k: meth.get(k, 0) for k in METHODS}}
        for key, val in want.items():
            if s.get(key) != val:
                err(f"summary.{key} does not match a recount ({val})")
    return errors


def derived_errors(T, dcs):
    errors = []
    err = errors.append

    def leaf(tid, *path):
        try:
            lf = at(T[tid]["values"], path)
        except (KeyError, TypeError):
            return None
        if not (is_obj(lf) and finite(lf.get("value")) and is_obj(lf.get("provenance"))):
            return None
        t = lf["provenance"].get("tolerance")
        if t is not None and not (is_obj(t) and finite(t.get("plusMinus"))):
            return None  # malformed: layer 1 or the finiteness check reports it
        return lf

    def tol(lf):
        t = lf["provenance"].get("tolerance")
        return t["plusMinus"] if t is not None else 0

    def rank(lf):
        p = lf["provenance"]
        c = p.get("confidence")
        return CONF_RANK["measured"] if p.get("kind") == "measured" else (CONF_RANK.get(c, -1) if is_str(c) else -1)

    def check(tid, c, o, inputs, value, tolerance, rnd, exact_conf=True):
        lf = leaf(tid, c, o)
        if lf is None:
            return
        p, where = lf["provenance"], f"{tid}[{c}/{o}]"
        expect = rnd(value)
        if p.get("kind") == "measured":
            allowed = tol(lf) + (tolerance if tolerance is not None else 0)
            if abs(lf["value"] - expect) > allowed + 1e-6:
                err(f"{where}: measured {lf['value']} disagrees with its inputs ({expect}) by more than {allowed}")
            return
        if p.get("kind") != "estimated":
            return
        if p.get("method") != "derived" or p.get("source") != "derived":
            err(f"{where}: a derived token's estimated cell must be method derived, source derived")
            return
        if abs(lf["value"] - expect) > 1e-6:
            err(f"{where}: derived value {lf['value']} but its inputs give {expect}")
        if tolerance is not None and abs(tol(lf) - up(tolerance)) > 1e-6:
            err(f"{where}: derived tolerance {tol(lf)} but the worst-case rule gives {up(tolerance)}")
        lowest = min(rank(x) for x in inputs)
        r = rank(lf)
        if r > lowest or (exact_conf and r != min(lowest, CONF_RANK["medium"])):
            err(f"{where}: derived confidence {p.get('confidence')!r} does not equal the lowest confidence among its inputs")

    r1 = lambda x: round(x + 1e-9, 1)
    r2 = lambda x: round(x + 1e-9, 2)
    same = lambda x: x
    names = ["keyboard.inset.side", "key.gap.horizontal", "keyboard.keyArea.height", "keyboard.inset.top", "key.letter.height",
             "key.gap.vertical", "suggestionBar.height", "keyboard.keyArea.width", "key.letter.width", "key.modeSwitch.width",
             "key.utility.width", "key.return.width"]
    for c, dc in dcs.items():
        if not (is_obj(dc) and is_obj(dc.get("screen")) and is_num(dc["screen"].get("width")) and is_num(dc["screen"].get("height"))
                and isinstance(dc.get("homeIndicator"), bool)):
            continue
        for o in ("portrait", "landscape"):
            L = {n: leaf(n, c, o) for n in names}
            if any(x is None for x in L.values()):
                continue
            v = {n: x["value"] for n, x in L.items()}
            e = {n: tol(x) for n, x in L.items()}
            W = dc["screen"]["width"] if o == "portrait" else dc["screen"]["height"]
            S, G = "keyboard.inset.side", "key.gap.horizontal"
            A, Tp, H, R, B = "keyboard.keyArea.height", "keyboard.inset.top", "key.letter.height", "key.gap.vertical", "suggestionBar.height"
            K, LW = "keyboard.keyArea.width", "key.letter.width"
            check(K, c, o, [L[S]], W - 2 * v[S], 2 * e[S], same)
            check(LW, c, o, [L[K], L[G]], (v[K] - 9 * v[G]) / 10, (e[K] + 9 * e[G]) / 10, r2)
            check("keyboard.inset.bottom", c, o, [L[A], L[Tp], L[H], L[R]], v[A] - v[Tp] - 4 * v[H] - 3 * v[R],
                  e[A] + e[Tp] + 4 * e[H] + 3 * e[R], same)
            check("keyboard.totalHeight", c, o, [L[B], L[A]], v[B] + v[A], e[B] + e[A], same)
            check("popup.key.riseLimit", c, o, [L[B], L[Tp]], v[B] + v[Tp], e[B] + e[Tp], same)
            n = 1 if dc["homeIndicator"] else 2
            M, U, Rt = "key.modeSwitch.width", "key.utility.width", "key.return.width"
            check("key.space.width", c, o, [L[K], L[M], L[U], L[Rt], L[G]], v[K] - v[M] - n * v[U] - v[Rt] - (n + 2) * v[G],
                  e[K] + e[M] + n * e[U] + e[Rt] + (n + 2) * e[G], r1)
            for tid in ("key.shift.width", "key.delete.width", M, U, Rt):
                lf = leaf(tid, c, o)
                if lf is None or lf["provenance"].get("kind") != "estimated":
                    continue
                m = re.search(r"key\.letter\.width \* ([0-9.]+)$", str(lf["provenance"].get("derivation", "")))
                if not m:
                    err(f"{tid}[{c}/{o}]: derivation is not 'key.letter.width * <ratio>'")
                else:
                    # the ratio's own confidence is not stored, so only "no more than the letter width" is checked
                    check(tid, c, o, [L[LW]], v[LW] * float(m.group(1)), None, r1, exact_conf=False)
    for tid in ("key.function.fillPressed", "popup.fill"):
        for app in ("light", "dark"):
            a, b = leaf_any(T, tid, app), leaf_any(T, "key.letter.fill", app)
            if a is None or b is None:
                continue
            p, q = a["provenance"], b["provenance"]
            if p.get("kind") != "estimated":
                continue
            if not (j_equal(p.get("method"), "derived") and j_equal(p.get("source"), "derived")):
                err(f"{tid}[{app}]: must be method derived, source derived")
                continue
            if a.get("value") != b.get("value"):
                err(f"{tid}[{app}]: derived from key.letter.fill but differs ({a.get('value')} vs {b.get('value')})")
            if (p.get("tolerance") or {}).get("plusMinus") != ((q.get("tolerance") or {}).get("plusMinus", 0) if is_obj(q.get("tolerance")) else 0):
                err(f"{tid}[{app}]: tolerance differs from key.letter.fill's")
            if q.get("kind") == "estimated" and p.get("confidence") != q.get("confidence"):
                err(f"{tid}[{app}]: confidence differs from key.letter.fill's")
    return errors


def leaf_any(T, tid, key):
    try:
        lf = T[tid]["values"][key]
    except (KeyError, TypeError):
        return None
    return lf if is_obj(lf) and is_obj(lf.get("provenance")) and (lf["provenance"].get("tolerance") is None or is_obj(lf["provenance"]["tolerance"])) else None


# --------------------------------------------------------------- main
def main(argv):
    args = argv[1:]
    if not args or args[0].startswith("-"):
        print(__doc__)
        return 2
    path, opts, i = args[0], {}, 1
    while i < len(args):
        if args[i] in ("--schema", "--expect-sha256") and i + 1 < len(args):
            opts[args[i]] = args[i + 1]
            i += 2
        elif args[i] == "--no-measured":
            opts["--no-measured"] = True
            i += 1
        else:
            print("unknown or incomplete option", args[i])
            return 2
    try:
        raw = open(path, "rb").read()
        schema = json.load(open(opts["--schema"])) if "--schema" in opts else None
    except (OSError, ValueError) as e:
        print(f"cannot read input: {e}")
        return 2
    errors = []
    digest = hashlib.sha256(raw).hexdigest()
    print("sha256", digest)
    if "--expect-sha256" in opts and opts["--expect-sha256"].lower() != digest:
        errors.append(f"sha256 {digest} does not match the pinned {opts['--expect-sha256']}")
    ids = schema_ids(schema) if schema is not None else None
    if schema is not None and ids is None:
        errors.append("the schema carries no id lists; is it the one generated with this token set?")
    try:
        doc = json.loads(raw)
    except ValueError as e:
        errors.append(f"not JSON: {e}")
        doc = None
    if doc is not None:
        for name, fn in (("schema mirror", lambda: mirror_errors(doc, ids)),
                         ("extra checks", lambda: extra_errors(doc, opts.get("--no-measured", False)))):
            try:
                errors.extend(fn())
            except Exception as e:  # fail closed, but still report what was found
                errors.append(f"{name} could not finish on this input ({type(e).__name__}: {e})")
        if schema is not None:
            try:
                import jsonschema
            except ImportError:
                print("note: jsonschema not installed; the schema cross-check was skipped (the schema mirror above ran).")
            else:
                for e in jsonschema.Draft202012Validator(schema).iter_errors(doc):
                    errors.append("schema: " + "/".join(str(p) for p in e.absolute_path) + ": " + e.message[:200])
    for e in errors:
        print("FAIL", e)
    print(f"{len(errors)} error(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
